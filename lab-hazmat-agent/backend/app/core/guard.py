"""控制类指令拦截。

设计取舍（对应开发文档 §7.3）：预检只拦「高置信」的祈使句，宁漏勿错杀——
"资质过期了该怎么改状态"是咨询，绝不能拒；"把李某的资质有效期改到明年"才拒绝。
低置信的问法交给 system prompt 由模型判断。

**这是一个正则 denylist，原理上不可能是完备的**（"开除""更新""变更"总会有漏网的动词）。
它的定位是第一道便宜的粗筛，真正的兜底是 system prompt 第 5 条 + 只读护栏 + 只读账号。
所以这里追求的是「高置信才拦」，而不是「拦得住一切」。

历史修正（两轮实测暴露的问题）：
- 原实现用「能否/可以/需要/应该」作为**放行**依据，但情态词不区分咨询与请求：
  「能否把王某的门禁权限注销掉」是对系统的写请求，却被放行。情态词已从放行词表移除。
- 改成「控制意图优先、咨询作例外」的判定顺序。原顺序是咨询优先，
  结果「帮我把…有效期改到明年」因为出现"有效期"而被当成咨询放行。
"""
from __future__ import annotations

import re

REFUSAL = (
    "本系统是只读问答系统，只有查询权限，不能修改资质、台账、授权或导出名单，也不能开门放行。\n"
    "这类操作请通过实验室安全负责人或学校安全管理平台走人工审批流程办理。\n"
    "我可以帮你查：某人的资质状态与有效期、某人某时能否进入某实验室、"
    "某实验室某时段的进入情况、台账与领用记录是否一致。"
)

# 数据改动 / 门禁控制的动词
_VERBS = (
    r"改|修改|更正|改成|改到|变更|调整|更新|延|续期|续签|展期|顺延|"
    r"撤销|吊销|注销|解绑|解除|开除|移除|踢出|移出|"
    r"报损|报废|删除|核销|清空|作废|覆盖|"
    r"导出|下载|拷出|"
    r"开门|开闸|放行|解锁|"
    r"新增|添加|录入|写入|导入|补录|"
    r"授予|设定|设置|重置|启用|禁用|开通|关闭|"
    r"借给|借出|外借|借用|归还|退还|登记"
)

# 受控对象：出现这些词说明动的是一条真实记录，而不是在问流程
_OBJECTS = (
    r"记录|名单|台账|资质|证书|证件|合格证|授权|权限|门禁|库存|结存|数据|条目|状态|有效期"
)

# 祈使前缀
_IMPERATIVE = r"(把|将|给|帮我|帮忙|麻烦|替我|请|去)"

# 被动 / 询问状态的写法，不应视为控制指令
_PASSIVE = re.compile(r"(被|已|是否|有没有|有没有人|谁).{0,6}(" + _VERBS + r")")

_HIGH_CONFIDENCE = [
    # A. 祈使前缀 + 控制动词：把李某的资质改到明年 / 帮我把门禁撤销
    re.compile(rf"{_IMPERATIVE}[^。？！]{{0,24}}(?:{_VERBS})"),
    # B. 控制动词 + 完成标记：这瓶丙酮报损掉 / 把记录删除掉（无前缀也能识别）
    re.compile(rf"(?:{_VERBS})(掉|了|成|完|掉。|掉！)"),
    # C. 控制动词 + 受控对象：删除王某的违规记录 / 终止其授权
    re.compile(rf"(?:{_VERBS})[^。？！]{{0,12}}(?:{_OBJECTS})"),
    # D. 句首就是控制动词：删除王某的违规记录
    re.compile(rf"^\s*(?:{_IMPERATIVE})?(?:{_VERBS})"),
    # E. 直接执行写语句
    re.compile(r"(执行|运行|跑一下|直接给我跑)\s*(UPDATE|DELETE|INSERT|DROP|ALTER|TRUNCATE)", re.I),
    re.compile(r"\b(UPDATE|DELETE|INSERT|DROP|ALTER|TRUNCATE)\s+[A-Za-z_]+\s+SET\b", re.I),
    # F. 远程操作门禁
    re.compile(r"远程[^。？！]{0,20}(门|开|关|锁|解锁|闸)"),
]

# 纯 how-to / 规则询问。命中且无祈使前缀时，视为咨询而非控制——
# 用于放过「报损需要什么流程」「授权撤销要走哪些手续」这类问法。
# 刻意不含情态词（能否/可以/需要/应该），它们同样出现在写请求里。
_ADVISORY = re.compile(
    r"(怎么|如何|怎样|为什么|"
    r"什么流程|什么手续|什么规定|什么要求|什么标准|什么条件|"
    r"什么情况|什么情形|哪些情况|哪些情形|哪些条件|"
    r"该怎么办|如何处理|如何处置|如何办理|怎么处理|怎么改|"
    r"规定|制度|标准|规范|依据|流程|手续|"
    r"多久|多长|期限|有效期|"
    r"是否必须|需要几个|要不要|能不能|可以不可以)"
)


def detect_control_intent(question: str) -> str | None:
    """命中高置信控制指令时返回拒绝话术；否则返回 None 交给 Agent。"""
    q = question.strip()
    if not q:
        return None

    matched = any(p.search(q) for p in _HIGH_CONFIDENCE)
    if not matched:
        return None

    # 例外 1：被动/询问写法——「王某的授权被撤销了吗」是在问状态，不是在改数据
    if _PASSIVE.search(q):
        return None

    # 例外 2：明确的 how-to / 规则询问，且没有祈使前缀
    has_imperative = re.search(rf"{_IMPERATIVE}[^。？！]{{0,24}}(?:{_VERBS})", q) is not None
    if not has_imperative and _ADVISORY.search(q):
        return None

    return REFUSAL
